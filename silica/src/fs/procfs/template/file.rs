//! ProcFS File Template and Operations.

use alloc::{boxed::Box, vec::Vec};

use crate::{
    api::errno::{Errno, Result},
    fs::vfs::{FileOps, INodeAttr, Mode, NodeOps, OpenFlags, SeekAnchor},
};

/// Operations provided by a virtual procfs file.
pub trait ProcFileOps: Send + Sync + 'static {
    /// Generates or reads content bytes for this file.
    fn generate_content(&self) -> Vec<u8>;

    /// Handles write operations for writable procfs files (e.g. sysctls).
    fn write_content(&self, _data: &[u8]) -> Result<()> {
        crate::return_errno!(EROFS, "procfs file is read-only");
    }
}

/// A node operations adapter wrapping any `ProcFileOps`.
pub struct ProcFileNodeOps<T: ProcFileOps> {
    inner: T,
    mode: Mode,
}

/// Convenience alias aligned with Asterinas/Silica conventions.
pub type ProcFile<T> = ProcFileNodeOps<T>;

impl<T: ProcFileOps> ProcFileNodeOps<T> {
    pub fn new_with_mode(inner: T, mode: Mode) -> Self {
        Self {
            inner,
            mode: Mode::FILE | mode,
        }
    }

    pub fn new_ro(inner: T) -> Self {
        Self {
            inner,
            mode: Mode::FILE | Mode::RUSR | Mode::RGRP | Mode::ROTH,
        }
    }

    pub fn new_rw(inner: T) -> Self {
        Self {
            inner,
            mode: Mode::FILE | Mode::RUSR | Mode::WUSR | Mode::RGRP | Mode::ROTH,
        }
    }
}

impl<T: ProcFileOps> NodeOps for ProcFileNodeOps<T> {
    fn open(&self, flags: OpenFlags) -> Result<Box<dyn FileOps>> {
        if flags.contains(OpenFlags::WRITE) && !self.mode.contains(Mode::WUSR) {
            crate::return_errno!(EPERM, "file is read-only");
        }
        let content = self.inner.generate_content();
        Ok(Box::new(DynamicProcFileOps::new(content)))
    }

    fn getattr(&self) -> Result<INodeAttr> {
        Ok(INodeAttr {
            size: 0,
            mode: Mode::FILE | self.mode,
            nlink: 1,
            uid: 0,
            gid: 0,
            rdev: 0,
        })
    }
}

/// Closure-based adapter for simple dynamic procfs files.
pub struct CallbackProcFileOps<F: Fn() -> Vec<u8> + Send + Sync + 'static> {
    generator: F,
}

impl<F: Fn() -> Vec<u8> + Send + Sync + 'static> CallbackProcFileOps<F> {
    pub fn new(generator: F) -> Self {
        Self { generator }
    }
}

impl<F: Fn() -> Vec<u8> + Send + Sync + 'static> ProcFileOps for CallbackProcFileOps<F> {
    fn generate_content(&self) -> Vec<u8> {
        (self.generator)()
    }
}

/// Convenience alias and constructor for dynamic closure-based procfs files.
pub type DynamicProcFileNodeOps<F> = ProcFileNodeOps<CallbackProcFileOps<F>>;

impl<F: Fn() -> Vec<u8> + Send + Sync + 'static> DynamicProcFileNodeOps<F> {
    pub fn new(generator: F) -> Self {
        Self::new_ro(CallbackProcFileOps::new(generator))
    }
}

/// File operations for reading/seeking from an in-memory generated byte buffer.
pub struct DynamicProcFileOps {
    data: Vec<u8>,
}

impl DynamicProcFileOps {
    pub fn new(data: Vec<u8>) -> Self {
        Self { data }
    }
}

impl FileOps for DynamicProcFileOps {
    fn read(&self, offset: u64, buf: &mut [u8]) -> Result<usize> {
        let offset = offset as usize;
        if offset >= self.data.len() {
            return Ok(0);
        }
        let available = &self.data[offset..];
        let copy_len = buf.len().min(available.len());
        buf[..copy_len].copy_from_slice(&available[..copy_len]);
        Ok(copy_len)
    }

    fn write(&self, _offset: u64, _buf: &[u8]) -> Result<usize> {
        crate::return_errno!(EROFS, "procfs is read-only");
    }

    fn seek(&self, curr_offset: u64, anchor: SeekAnchor) -> Result<u64> {
        let len = self.data.len() as i64;
        let new_offset = match anchor {
            SeekAnchor::Start(pos) => pos as i64,
            SeekAnchor::Current(delta) => curr_offset as i64 + delta,
            SeekAnchor::End(delta) => len + delta,
        };
        if new_offset < 0 {
            return Err(Errno::EINVAL);
        }
        Ok(new_offset as u64)
    }
}
